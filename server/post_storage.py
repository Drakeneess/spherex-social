"""Budgeted image derivatives for community posts; scientific FITS are untouched.

Four photos use at most 4 * (650 + 100) KiB = 3000 KiB of media
objects, below the strict 3 MiB cap. Input originals are never stored.
"""
from __future__ import annotations

import base64
import io
from dataclasses import dataclass
from uuid import UUID

from fastapi import HTTPException
from PIL import Image, ImageOps, UnidentifiedImageError

from sky_storage import _put_bytes, _get_bytes, _s3_settings, _client, LOCAL_STORE

MAX_INPUT = 3 * 1024 * 1024
MAX_PIXELS = 16_000_000
FULL_MAX_EDGE = 1600
THUMB_MAX_EDGE = 400
MAX_FULL_BYTES = 650 * 1024
MAX_THUMB_BYTES = 100 * 1024
MAX_POST_BYTES = 3 * 1024 * 1024
PREFIXES = (
    "data:image/png;base64,",
    "data:image/jpeg;base64,",
    "data:image/webp;base64,",
)
ROOT = "social/media/v1/"
QUALITY_STEPS = (86, 80, 74, 68, 62, 58)
THUMB_QUALITY_STEPS = (78, 70, 62, 54)


@dataclass(frozen=True)
class OptimizedPhoto:
    full: bytes
    thumbnail: bytes

    @property
    def stored_size(self) -> int:
        return len(self.full) + len(self.thumbnail)


def media_key(media_id: UUID) -> str:
    return f"{ROOT}{media_id}.webp"


def thumbnail_key(key: str) -> str:
    _check_key(key)
    return key[:-5] + ".thumb.webp"


def _check_key(key: str) -> None:
    if not key.startswith(ROOT) or not key.endswith(".webp") or ".thumb." in key:
        raise ValueError("Invalid image reference")
    # All storage paths are generated by our backend and contain exactly one UUID.
    try:
        UUID(key[len(ROOT):-5])
    except (ValueError, AttributeError) as exc:
        raise ValueError("Invalid image reference") from exc


def _encode_budget(
    image: Image.Image, maximum_edge: int, limit: int,
    sizes: tuple[int, ...], qualities: tuple[int, ...],
) -> bytes | None:
    """Prefer resolution, then the highest WebP quality that fits the budget.

    Do not silently turn a noisy astronomy image into a low-quality block
    artifact: fail politely if no allowed quality/size combination can fit.
    """
    for edge in sizes:
        scaled = image.copy()
        scaled.thumbnail((min(edge, maximum_edge),) * 2, Image.Resampling.LANCZOS)
        for quality in qualities:
            out = io.BytesIO()
            scaled.save(out, format="WEBP", quality=quality, method=4)
            data = out.getvalue()
            if len(data) <= limit:
                return data
    return None


def decode_image(data_url: str) -> OptimizedPhoto:
    prefix = next((p for p in PREFIXES if data_url.startswith(p)), None)
    if prefix is None:
        raise HTTPException(status_code=422, detail="Formatos admitidos: JPEG, PNG y WebP")
    encoded = data_url[len(prefix):]
    if len(encoded) > (MAX_INPUT * 4 // 3 + 8):
        raise HTTPException(status_code=413, detail="Imagen de entrada demasiado grande (máximo 3 MiB)")
    try:
        raw = base64.b64decode(encoded, validate=True)
        if not raw or len(raw) > MAX_INPUT:
            raise ValueError("oversized")
        with Image.open(io.BytesIO(raw)) as source:
            if source.format not in ("JPEG", "PNG", "WEBP"):
                raise ValueError("unsupported image")
            if source.width < 1 or source.height < 1 or source.width * source.height > MAX_PIXELS:
                raise ValueError("unsafe dimensions")
            image = ImageOps.exif_transpose(source)
            # New pixels and no EXIF/ICC/GPS metadata copied to published images.
            image = image.convert(
                "RGBA" if "A" in image.getbands() or "transparency" in image.info else "RGB"
            )
            full = _encode_budget(
                image, FULL_MAX_EDGE, MAX_FULL_BYTES,
                (1600, 1440, 1280, 1120, 960), QUALITY_STEPS,
            )
            thumb = _encode_budget(
                image, THUMB_MAX_EDGE, MAX_THUMB_BYTES,
                (400, 360, 320, 280), THUMB_QUALITY_STEPS,
            )
    except (ValueError, OSError, UnidentifiedImageError,
            Image.DecompressionBombError, base64.binascii.Error) as exc:
        raise HTTPException(status_code=422, detail="Imagen inválida o demasiado grande") from exc
    if full is None or thumb is None:
        raise HTTPException(
            status_code=413,
            detail="La imagen contiene demasiado detalle para la calidad mínima admitida. "
                   "Prueba con una fotografía menos ruidosa o un recorte más pequeño.",
        )
    result = OptimizedPhoto(full=full, thumbnail=thumb)
    if result.stored_size > MAX_FULL_BYTES + MAX_THUMB_BYTES:
        raise HTTPException(status_code=413, detail="Presupuesto de imagen excedido")
    return result


def _validate_webp(data: bytes, maximum: int) -> None:
    if not data or len(data) > maximum or not data.startswith(b"RIFF") or data[8:12] != b"WEBP":
        raise ValueError("Invalid encoded WebP image")


def put_post_image(media_id: UUID, photo: OptimizedPhoto) -> str:
    """Save both variants; remove partial writes if S3/local storage fails."""
    _validate_webp(photo.full, MAX_FULL_BYTES)
    _validate_webp(photo.thumbnail, MAX_THUMB_BYTES)
    if photo.stored_size > MAX_FULL_BYTES + MAX_THUMB_BYTES:
        raise ValueError("Image storage budget exceeded")
    key = media_key(media_id)
    try:
        _put_bytes(key, photo.full, "image/webp")
        _put_bytes(thumbnail_key(key), photo.thumbnail, "image/webp")
    except Exception:
        try:
            delete_post_image(key)
        except Exception:
            pass
        raise
    return key


def _is_missing_object(exc: Exception) -> bool:
    if isinstance(exc, FileNotFoundError):
        return True
    # boto3 returns ClientError for an absent object. Other S3 failures are
    # propagated instead of silently masquerading as legacy files.
    response = getattr(exc, "response", None)
    if isinstance(response, dict):
        code = response.get("Error", {}).get("Code", "")
        return str(code) in ("NoSuchKey", "404", "NotFound")
    return False


def get_post_image(key: str, variant: str = "full") -> bytes:
    _check_key(key)
    if variant not in ("full", "thumbnail"):
        raise ValueError("Invalid image variant")
    chosen = thumbnail_key(key) if variant == "thumbnail" else key
    try:
        raw = _get_bytes(chosen, MAX_THUMB_BYTES if variant == "thumbnail" else MAX_INPUT)
    except Exception as exc:
        if variant != "thumbnail" or not _is_missing_object(exc):
            raise
        # Images uploaded before this feature have no generated thumbnail.
        raw = _get_bytes(key, MAX_INPUT)
    _validate_webp(raw, MAX_INPUT)
    return raw


def delete_post_image(key: str) -> None:
    """Always delete both variants; deleting a legacy absent thumb is safe."""
    _check_key(key)
    keys = (key, thumbnail_key(key))
    settings = _s3_settings()
    if settings is None:
        for obj in keys:
            (LOCAL_STORE / obj).unlink(missing_ok=True)
    else:
        endpoint, bucket, region, access, secret = settings
        response = _client(endpoint, access, secret, region).delete_objects(
            Bucket=bucket, Delete={"Objects": [{"Key": obj} for obj in keys], "Quiet": True},
        )
        if response.get("Errors"):
            raise RuntimeError("Some post images could not be deleted")
